def set_run_font(run, size: int = 16, bold: bool = False) -> None:
    run.bold = bold
    run.font.name = "TH Sarabun New"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "TH Sarabun New")
    run.font.size = Pt(size)


def make_empty_after(paragraph: Paragraph) -> Paragraph:
    new_p = deepcopy(paragraph._p)
    for child in list(new_p):
        new_p.remove(child)
    paragraph._p.addnext(new_p)
    return Paragraph(new_p, paragraph._parent)


def insert_text_after(paragraph: Paragraph, text: str, *, size: int = 16, bold: bool = False, style: str | None = None) -> Paragraph:
    new_para = make_empty_after(paragraph)
    if style:
        try:
            new_para.style = style
        except Exception:
            pass
    run = new_para.add_run(text)
    set_run_font(run, size=size, bold=bold)
    return new_para


def remove_paragraph(paragraph: Paragraph) -> None:
    element = paragraph._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)


def clean_text(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip())


def doc_code_from_name(name: str) -> str | None:
    match = re.match(r"^(\d+\.\d+)_", name)
    return match.group(1) if match else None


def replace_terms(doc: Document) -> None:
    for paragraph in doc.paragraphs:
        text = paragraph.text
        if "local UAT" in text or "ใน local UAT" in text:
            new_text = text.replace("ใน local UAT", "ในระบบ").replace("local UAT", "ระบบ")
            if new_text != text:
                for run in paragraph.runs:
                    run.text = ""
                run = paragraph.add_run(new_text)
                set_run_font(run)


def remove_existing_guidance(paragraphs: list[Paragraph]) -> None:
    for paragraph in list(paragraphs):
        if clean_text(paragraph.text) in {USAGE_HEADING, JOURNAL_HEADING}:
            remove_paragraph(paragraph)


def find_idx(paragraphs: list[Paragraph], target: str) -> int | None:
    for idx, paragraph in enumerate(paragraphs):
        if clean_text(paragraph.text) == target:
            return idx
    return None


def enrich_doc(path: Path) -> bool:
    code = doc_code_from_name(path.name)
    if not code or code not in GUIDANCE:
        return False
    doc = Document(str(path))
    replace_terms(doc)
    remove_existing_guidance(doc.paragraphs)
    paragraphs = doc.paragraphs
    menu_idx = find_idx(paragraphs, MENU_HEADING)
    steps_idx = find_idx(paragraphs, STEP_HEADING)
    journal_read_idx = find_idx(paragraphs, JOURNAL_READ)

    current = None
    if menu_idx is not None and menu_idx > 0:
        anchor = paragraphs[menu_idx - 1]
        current = insert_text_after(anchor, USAGE_HEADING, size=16, bold=True)
        for text in GUIDANCE[code]["usage"]:
            current = insert_text_after(current, text, size=16)

    if journal_read_idx is not None:
        current = paragraphs[journal_read_idx]
        journal_heading_para = insert_text_after(current, JOURNAL_HEADING, size=16, bold=True)
        current = journal_heading_para
        for text in GUIDANCE[code]["journal"]:
            current = insert_text_after(current, text, size=16)

    doc.save(str(path))
    return True


def render(paths: list[Path]) -> None:
    if not paths:
        return
    cmd = [str(SOFFICE), "--headless", "--convert-to", "pdf", "--outdir", str(PDF_DIR), *map(str, paths)]
    subprocess.run(cmd, check=True)


def main() -> None:
    updated: list[Path] = []
    for path in sorted(DOCX_DIR.glob("*.docx")):
        if enrich_doc(path):
            updated.append(path)
    render(updated)
    print(f"enriched {len(updated)} docs")


if __name__ == "__main__":
    main()
